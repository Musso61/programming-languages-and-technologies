
// Обычное приветствие
export function simpleGreeting(name) {
    return `Привет, ${name}! Добро пожаловать!`;
}

// Дружеское приветствие
export function friendlyGreeting(name) {
    return `Привет, ${name}! 😊 Очень рады тебя видеть! Желаем отличного дня!`;
}

// Официальное приветствие
export function officialGreeting(name) {
    return `Уважаемый(ая) ${name}! Приветствуем Вас и желаем успехов!`;
}
